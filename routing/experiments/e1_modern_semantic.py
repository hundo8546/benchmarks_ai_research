"""
E1 — Modern Semantic Detector Replacement.
Compares CLIP ViT-B/32 (S1), SigLIP2 (S2), DINOv2 (S3) as semantic backbone.
Evaluates at train fractions: 50%, 25%, 10%, 5%, 1%.
Computes routing metrics for each backbone × dataset × fraction.

Produces: results/e1_semantic_results.csv, results/e1_figure_data.csv

Pre-requisites:
  - Feature CSVs generated by:
      extractors/extract_siglip2.py --dataset <D>
      extractors/extract_dinov2.py --dataset <D>
  - CLIP features already generated (clip_features.csv etc.)

Usage:
    python e1_modern_semantic.py [--datasets GenBuster SD14 BigGAN]
"""
import argparse
import os
import sys

import joblib
import numpy as np
import pandas as pd
from sklearn.linear_model import LogisticRegression
from sklearn.metrics import accuracy_score, balanced_accuracy_score, roc_auc_score
from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))
sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "extractors"))
from extractors.common import (
    DATASETS, RESULTS_DIR, ROUTING_BASE, ensure_results_dir,
    bootstrap_ci, balanced_accuracy, auroc, calibration_ece,
    LATENCY_CHEAP_MS,
)

FRACTIONS = [0.50, 0.25, 0.10, 0.05, 0.01]

SEMANTICS = {
    "CLIP": {"feat_prefix": "clip_features", "latency_col": "latency_clip_ms"},
    "SigLIP2": {"feat_prefix": "siglip2_features", "latency_col": "latency_siglip2_ms"},
    "DINOv2": {"feat_prefix": "dinov2_features", "latency_col": "latency_dinov2_ms"},
}


def load_features(feat_file, latency_col=None):
    df = pd.read_csv(feat_file)
    drop = {"path", "y_true", "generator"}
    if latency_col:
        drop.add(latency_col)
    for c in df.columns:
        if c.startswith("latency_"):
            drop.add(c)
    feat_cols = [c for c in df.columns if c.startswith("f")]
    return df, feat_cols


def train_probe_at_fraction(feat_df, feat_cols, frac, val_idx=None):
    """Train a logistic regression probe. Returns (clf, scaler, val_idx)."""
    X = feat_df[feat_cols].values.astype(np.float32)
    y = feat_df["y_true"].values.astype(int)

    if val_idx is None:
        all_idx = np.arange(len(X))
        train_idx_full, val_idx = train_test_split(
            all_idx, test_size=0.30, random_state=42, stratify=y
        )
    else:
        train_idx_full = np.array([i for i in range(len(X)) if i not in set(val_idx)])

    # Sub-sample train at fraction
    n_total = len(train_idx_full)
    n_train = max(4, int(n_total * frac))
    y_train_full = y[train_idx_full]
    pos = train_idx_full[y_train_full == 1]
    neg = train_idx_full[y_train_full == 0]
    rng = np.random.default_rng(42)
    n_pos = max(2, n_train // 2)
    n_neg = max(2, n_train - n_pos)
    sampled_idx = np.concatenate([
        rng.choice(pos, min(n_pos, len(pos)), replace=False),
        rng.choice(neg, min(n_neg, len(neg)), replace=False),
    ])

    scaler = StandardScaler()
    X_tr = scaler.fit_transform(X[sampled_idx])
    X_val = scaler.transform(X[val_idx])
    y_tr = y[sampled_idx]
    y_val = y[val_idx]

    clf = LogisticRegression(max_iter=2000, C=0.1, random_state=42)
    clf.fit(X_tr, y_tr)

    y_pred = clf.predict(X_val)
    y_prob = clf.predict_proba(X_val)[:, 1]

    metrics = {
        "n_train": len(sampled_idx),
        "accuracy": float(accuracy_score(y_val, y_pred)),
        "balanced_accuracy": float(balanced_accuracy_score(y_val, y_pred)),
        "auroc": float(roc_auc_score(y_val, y_prob)) if len(np.unique(y_val)) > 1 else float("nan"),
        "ece": float(calibration_ece(y_val, y_prob)),
    }
    return clf, scaler, val_idx, y_pred, y_prob, metrics


def routing_metrics(df_val, y_clip_pred, artifact_preds_col="y_cnn"):
    """Compute agreement rate and conditional accuracy metrics."""
    y_cnn = df_val[artifact_preds_col].values
    y_true = df_val["y_true"].values
    disagree = (y_cnn != y_clip_pred).astype(int)

    agree_mask = disagree == 0
    dis_mask = disagree == 1

    agree_acc = float(np.mean(y_clip_pred[agree_mask] == y_true[agree_mask])) if agree_mask.sum() > 0 else float("nan")
    dis_acc = float(np.mean(y_clip_pred[dis_mask] == y_true[dis_mask])) if dis_mask.sum() > 0 else float("nan")

    # Escalation gain potential: how much does correct routing help on disagree cases
    gain_potential = agree_acc - dis_acc if not np.isnan(agree_acc) and not np.isnan(dis_acc) else float("nan")

    return {
        "agreement_rate": float(np.mean(agree_mask)),
        "cheap_path_accuracy": agree_acc,
        "hard_case_accuracy": dis_acc,
        "escalation_gain_potential": gain_potential,
    }


def parse_args():
    p = argparse.ArgumentParser()
    p.add_argument("--datasets", nargs="+", default=list(DATASETS.keys()))
    return p.parse_args()


def main():
    args = parse_args()
    ensure_results_dir()

    all_rows = []

    for ds_name in args.datasets:
        cfg = DATASETS[ds_name]
        print(f"\n=== {ds_name} ===")

        # Load artifact detector predictions for routing metrics
        cnnspot_csv = cfg.get("cnnspot_csv", "")
        df_cnn = None
        if os.path.exists(cnnspot_csv):
            df_cnn = pd.read_csv(cnnspot_csv)
            val_paths = np.load(cfg["val_paths"], allow_pickle=True)
            df_cnn_val = df_cnn[df_cnn["path"].isin(val_paths)].reset_index(drop=True)
        else:
            print(f"  Warning: CNNSpot CSV not found, skipping routing metrics")
            val_paths = None
            df_cnn_val = None

        # Fixed val_idx (same for all fractions/backbones within a dataset)
        common_val_idx = None

        for sem_name, sem_cfg in SEMANTICS.items():
            feat_file = os.path.join(ROUTING_BASE,
                                     f"{cfg['prefix']}{sem_cfg['feat_prefix']}.csv")
            if not os.path.exists(feat_file):
                print(f"  Missing features for {sem_name}: {feat_file}, skipping")
                continue

            print(f"\n  Backbone: {sem_name}")
            feat_df, feat_cols = load_features(feat_file, sem_cfg["latency_col"])

            # Establish fixed val split on first backbone
            if common_val_idx is None:
                X_tmp = feat_df[feat_cols].values.astype(np.float32)
                y_tmp = feat_df["y_true"].values.astype(int)
                all_idx = np.arange(len(X_tmp))
                _, val_idx = train_test_split(all_idx, test_size=0.30,
                                              random_state=42, stratify=y_tmp)
                common_val_idx = val_idx
            else:
                val_idx = common_val_idx

            for frac in FRACTIONS:
                clf, scaler, val_idx, y_pred, y_prob, metrics = train_probe_at_fraction(
                    feat_df, feat_cols, frac, val_idx=val_idx
                )

                # Routing metrics (requires CNN predictions on the same val set)
                rt_metrics = {}
                if df_cnn_val is not None:
                    # Align val paths
                    val_paths_set = set(feat_df.iloc[val_idx]["path"].values)
                    df_cnn_sub = df_cnn_val[df_cnn_val["path"].isin(val_paths_set)].reset_index(drop=True)
                    feat_val_paths = feat_df.iloc[val_idx]["path"].values
                    # Match ordering
                    path_to_idx = {p: i for i, p in enumerate(feat_val_paths)}
                    common_paths = [p for p in df_cnn_sub["path"].values if p in path_to_idx]
                    if common_paths:
                        cnn_aligned = df_cnn_sub.set_index("path").loc[common_paths, "y_cnn"].values
                        y_clip_arr = y_pred
                        rt_metrics = routing_metrics(
                            pd.DataFrame({"y_cnn": cnn_aligned[:len(y_clip_arr)],
                                          "y_true": feat_df.iloc[val_idx]["y_true"].values[:len(cnn_aligned)]}),
                            y_clip_arr[:len(cnn_aligned)]
                        )

                row = {
                    "dataset": ds_name,
                    "backbone": sem_name,
                    "train_fraction": frac,
                    **metrics,
                    **rt_metrics,
                }
                all_rows.append(row)
                print(f"    frac={frac:.2f}: acc={metrics['accuracy']:.3f}, "
                      f"bal_acc={metrics['balanced_accuracy']:.3f}, "
                      f"auroc={metrics['auroc']:.3f}, "
                      f"agree={rt_metrics.get('agreement_rate', 'N/A')}")

    df_out = pd.DataFrame(all_rows)
    out_file = os.path.join(RESULTS_DIR, "e1_semantic_results.csv")
    df_out.to_csv(out_file, index=False)
    print(f"\nSaved {out_file}")

    # Generate figure data: accuracy vs train_fraction per backbone
    fig_file = os.path.join(RESULTS_DIR, "e1_figure_data.csv")
    df_out.to_csv(fig_file, index=False)
    print(f"Saved figure data to {fig_file}")

    print("\nE1 complete.")


if __name__ == "__main__":
    main()
